"""Paired false-rejection evaluation with a private oracle and explicit budgets.

Offline runs validate the pipeline only. Reported paper results are not
regenerated by this file unless the matching inputs and live model are used.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path
import statistics

from .session import build_coordinator
from .structured.state import FeedbackState
from .structured.contracts import default_item, event_for
from .refinement.baselines import RankOnlyPolicy


class PrivateOracle:
    """Only verdicts cross into a diagnostic policy; labels never enter prompts."""
    def __init__(self, target: str, false_rejections: int = 0):
        if false_rejections < 0:
            raise ValueError("False-rejection budget must be nonnegative")
        self.target, self.remaining = target, false_rejections

    def verdict(self, entity: str) -> str:
        if entity == self.target:
            if self.remaining == 0:
                return "final_accept"
            self.remaining -= 1
        return "challenge"


def run_trajectory(initial: FeedbackState, target: str, *, strategy: str,
                   false_rejections: int = 0, budget: int = 20, client=None) -> dict:
    if budget < 1 or initial.snapshots and initial.version != 1:
        raise ValueError("Positive budget and a frozen initial state are required")
    if initial.feedback_items or initial.challenge_counts or initial.submissions:
        raise ValueError("All strategies must begin from the same unmodified initial state")
    oracle = PrivateOracle(target, false_rejections)
    scores = copy.deepcopy(initial.base_scores)
    if strategy == "no_feedback":
        correct = max(scores, key=scores.get) == target
        return {"strategy": strategy, "K": false_rejections, "success": correct,
                "interactions": 1 if correct else budget, "capped_interactions": 1 if correct else budget,
                "reference_only": True, "trajectory": []}
    rank_policy = None
    if strategy in {"top5", "downweighting", "revisit"}:
        rank_policy = RankOnlyPolicy(scores,
            {"top5": "STATIC_TOPK", "downweighting": "SOFT_DECAY", "revisit": "REVISIT_INSPECTION"}[strategy],
            budget=budget, k=min(5, len(scores)) if strategy == "top5" else None)
    elif strategy in {"full", "flat", "stateful_single_agent"}:
        coordinator = build_coordinator(copy.deepcopy(initial), client=client,
            config={"submission_budget": budget},
            representation="flat" if strategy != "full" else "rmg",
            delegate=strategy != "stateful_single_agent")
    else:
        raise ValueError("Unknown feedback strategy")
    success, trace, failure = False, [], None
    for interaction in range(1, budget + 1):
        if rank_policy:
            entity = rank_policy.leader()
            if entity is None:
                break
        else:
            entity = coordinator.state.snapshots[-1]["synthesis"]["selected_entity"]
        verdict = oracle.verdict(entity)
        if rank_policy:
            result = rank_policy.submit(f"review-{interaction}", entity, verdict)
        else:
            state = coordinator.state
            claim = next(c for c in state.claims.values() if c["kind"] == "root_role_global" and c["entity_ids"] == [entity])
            item = default_item(item_id="current-root", target_claim_id=claim["claim_id"],
                entity_ids=claim["entity_ids"], window_ids=claim["window_ids"],
                stance="support" if verdict == "final_accept" else "challenge")
            result = coordinator.submit(event_for(state, f"review-{interaction}", [item],
                event_type="final_accept" if verdict == "final_accept" else "comment"))
            if not result.get("committed"):
                failure = result["event_status"]
        trace.append({"interaction": interaction, "inspected_entity": entity,
                      "verdict": verdict, "result": result})
        if failure:
            break
        if verdict == "final_accept":
            success = True
            break
    count = trace[-1]["interaction"] if success else budget
    return {"strategy": strategy, "K": false_rejections, "success": success,
            "interactions": count if success else None, "capped_interactions": count,
            "failure": failure, "trajectory": trace,
            "execution_mode": "model_refinement" if client is not None and rank_policy is None else
                "offline_pipeline_only" if rank_policy is None else "rank_only_control"}


def summarize(rows: list[dict]) -> list[dict]:
    groups = {}
    for row in rows:
        groups.setdefault((row["strategy"], row["K"]), []).append(row)
    return [{"strategy": strategy, "K": k, "cases": len(values),
             "successes": sum(r["success"] for r in values),
             "success_rate_within_budget": sum(r["success"] for r in values) / len(values),
             "mean_capped_interactions": statistics.mean(r["capped_interactions"] for r in values)}
            for (strategy, k), values in sorted(groups.items())]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True, help="JSON entries: incident_id and public FeedbackState artifact path")
    parser.add_argument("--labels", type=Path, required=True, help="Private incident-to-service mapping, evaluator only")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--mode", choices=["offline", "live"], default="offline")
    parser.add_argument("--strategies", nargs="+", default=["full", "top5", "downweighting", "no_feedback"])
    parser.add_argument("--K", type=int, nargs="+", default=[0, 1, 3, 5])
    parser.add_argument("--budget", type=int, default=20)
    parser.add_argument("--model", default="gpt-4o-mini")
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError("Use a new output directory for each frozen run")
    entries = json.loads(args.manifest.read_text(encoding="utf-8"))
    labels = json.loads(args.labels.read_text(encoding="utf-8"))
    if len({e["incident_id"] for e in entries}) != len(entries):
        raise ValueError("Duplicate incident in the evaluation manifest")
    client = None
    if args.mode == "live":
        from root_teller.module2.llm import CachedJSONClient, load_api_settings
        client = CachedJSONClient(load_api_settings(Path("__environment_only__")), args.output / "model_cache",
                                  args.model, 0.0, 60, 0)
    rows = []
    for entry in entries:
        path = Path(entry["state"])
        if not path.is_absolute():
            path = args.manifest.parent / path
        state = FeedbackState.restore(json.loads(path.read_text(encoding="utf-8")))
        if state.raw["incident_id"] != entry["incident_id"]:
            raise ValueError("Manifest/state incident mismatch")
        target = labels[entry["incident_id"]]
        for strategy in args.strategies:
            for k in args.K:
                rows.append({"incident_id": entry["incident_id"], **run_trajectory(state, target,
                    strategy=strategy, false_rejections=k, budget=args.budget, client=client)})
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "trajectories.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    (args.output / "summary.json").write_text(json.dumps({"mode": args.mode,
        "status": "completed_pipeline_only" if args.mode == "offline" else "executed_model_evaluation",
        "budget": args.budget, "summary": summarize(rows)}, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
